# -*- coding: utf-8 -*-
"""A fresh card worktree gets surfaces/app/node_modules linked to the main repo's
(so tsc/app_shot run inside the guard), and reclaim removes ONLY the link - the
main repo's node_modules must survive. Self-sandboxing: throwaway repo + db."""
import os, sys, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))

SANDBOX = tempfile.mkdtemp()
from spine.storage import db
db.DBPATH = os.path.join(SANDBOX, "helmdeck.db")
from spine.storage import events
events.SET = os.path.join(SANDBOX, "settings.json")
db.init()

from cells.engineer.cards import dispatch
from spine.git.worktrees import reclaim_worktree

_fails = []


def check(cond, msg):
    print(("  ok  " if cond else "  FAIL ") + msg)
    if not cond:
        _fails.append(msg)


def git(repo, *args):
    r = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("git %s: %s" % (" ".join(args), r.stderr.strip()))


def main():
    repo = tempfile.mkdtemp()
    git(repo, "init"); git(repo, "symbolic-ref", "HEAD", "refs/heads/main")
    git(repo, "config", "user.email", "t@t.t"); git(repo, "config", "user.name", "t")
    app = os.path.join(repo, "surfaces", "app")
    os.makedirs(os.path.join(app, "node_modules", "pkg"))
    with open(os.path.join(app, "node_modules", "pkg", "index.js"), "w") as f:
        f.write("x")
    with open(os.path.join(app, "package.json"), "w") as f:
        f.write("{}")
    with open(os.path.join(repo, ".gitignore"), "w") as f:
        f.write("node_modules/\n")
    git(repo, "add", "-A"); git(repo, "commit", "-m", "init")

    t = {"id": "t-nm", "repo": repo, "branch": "card-nm", "task": "t",
         "lane": "done", "status": "needs_you"}
    db.track_put(t)
    wt = dispatch._ensure_worktree(t)
    t["worktree"] = wt
    check(os.path.isfile(os.path.join(wt, "surfaces", "app", "node_modules", "pkg", "index.js")),
          "new worktree resolves node_modules through the link")

    reclaim_worktree(t, force=True)
    check(not os.path.isdir(wt), "worktree reclaimed")
    check(os.path.isfile(os.path.join(app, "node_modules", "pkg", "index.js")),
          "main repo node_modules intact after reclaim")


main()
print()
if _fails:
    print("FAILED: %d check(s)" % len(_fails)); sys.exit(1)
print("ALL GREEN - node_modules linked at create, only the link removed at reclaim")
